"""
Depth Anything V2 pseudo-labelling for MINC-2500 patches. (Phase 3)

These pseudo-labels are **relative** depth, not metric. A 362x362 crop carries
no camera intrinsics, so there is no scale to recover. Every map is normalised
to [0, 1] per image and every docstring, log line and report sentence downstream
must say "relative". Metric calibration comes from NYUv2 and Tier 3 only.

Expected non-bug behaviour: flat-texture classes (``carpet``, ``fabric``,
``paper``) produce near-constant maps with faint texture ripple. A flat swatch
has no depth structure. Those patches contribute almost nothing to the depth
loss, which is a real limitation and is quantified by
:func:`depth_structure_report` rather than hidden.

Unresolved methodological problem — raise before Phase 8
--------------------------------------------------------
The depth half of the ablation is **confounded as specified**, and this is a
design problem, not a coding one.

The pseudo-labels here are generated by Depth Anything V2 — the same checkpoint
the shared encoder and the DPT depth head are initialised from. So the Phase 8
comparison "Model C vs Model A on depth metrics" measures how closely a
DA-V2-initialised student reproduces DA-V2's own output. That is
self-consistency, not depth accuracy. Both A and C will score well on AbsRel and
RMSE against these targets, and the comparison says little about whether joint
training helped depth.

It also breaks a claim the review document makes. The document promises **metric
depth in metres** and cites NYUv2 for scale calibration, but the build spec has
no NYUv2 phase — Phases 0-10 never touch real ground-truth depth. With SILog,
which is scale-invariant by construction, trained on relative pseudo-labels, the
pipeline as specified cannot produce metric depth and cannot report AbsRel or
RMSE against anything real.

Fix before the ablation runs: evaluate Models A and C on a NYUv2 test subset
with real ground-truth depth, and report the depth column from that, not from
pseudo-label agreement. The stiffness half of the ablation (C vs B) is sound and
is unaffected.

Storage note: maps are saved as float16 ``.npy``. At 364x364 that is ~265 KB per
image, so the full 35,000-image pass needs roughly 9 GB on disk.
"""

import time
from pathlib import Path
from typing import Dict, Iterable, Optional, Union

import numpy as np
import pandas as pd

from vise.config import get_logger

MODEL_ID = "depth-anything/Depth-Anything-V2-Small-hf"
SPLITS = ("train", "val", "test")

# A map whose predicted-depth range is below this (after per-image
# normalisation the range is 1.0 by construction, so this is measured on the
# RAW model output) carries essentially no depth structure.
FLAT_RANGE_THRESHOLD = 1e-3


def load_depth_pipeline(model_id: str = MODEL_ID, device: Optional[str] = None):
    """
    Build a ``transformers`` depth-estimation pipeline.

    Downloads ~100 MB on first call. The returned pipeline produces **relative**
    depth only.
    """
    from transformers import pipeline as hf_pipeline

    logger = get_logger("pseudo_depth")
    if device is None:
        import torch

        device = 0 if torch.cuda.is_available() else -1
    logger.info(
        "Loading %s (device=%s) — output is RELATIVE depth, not metric",
        model_id,
        "cuda:0" if device == 0 else "cpu",
    )
    return hf_pipeline("depth-estimation", model=model_id, device=device)


def normalise_depth(arr: np.ndarray) -> np.ndarray:
    """
    Normalise a raw depth map to [0, 1]. Absolute scale is meaningless on a crop,
    so only the within-image ordering is retained.

    A constant map (a perfectly flat swatch) would divide by zero; it is returned
    as all-zeros instead, which is the correct representation of "no depth
    structure" and is counted in the flat-map statistics.
    """
    arr = arr.astype(np.float32)
    lo, hi = float(arr.min()), float(arr.max())
    if hi - lo < 1e-12:
        return np.zeros_like(arr, dtype=np.float32)
    return (arr - lo) / (hi - lo)


def depth_path_for(image_path: str, out_dir: Union[str, Path]) -> Path:
    """
    Map ``images/<class>/<file>.jpg`` to ``<out_dir>/<class>/<file>.npy``,
    preserving the class subdirectory so the output tree mirrors the input.
    """
    p = Path(str(image_path).replace("\\", "/"))
    return Path(out_dir) / p.parent.name / f"{p.stem}.npy"


def generate(
    manifest: pd.DataFrame,
    minc_root: Union[str, Path],
    out_dir: Union[str, Path],
    pipe=None,
    batch_size: int = 8,
    limit: Optional[int] = None,
    overwrite: bool = False,
) -> pd.DataFrame:
    """
    Run Depth Anything V2 over the manifest's images, writing one float16 ``.npy``
    per image and returning the manifest with a ``depth_path`` column added.

    Existing files are skipped unless *overwrite*, so an interrupted run resumes.
    Timing and flat-map statistics are logged.

    Parameters
    ----------
    limit : int, optional
        Process only the first *limit* rows. Use this for the mandatory 64-image
        smoke test before launching the full pass.
    """
    from PIL import Image

    logger = get_logger("pseudo_depth")
    minc_root, out_dir = Path(minc_root), Path(out_dir)
    df = manifest.iloc[:limit].copy() if limit else manifest.copy()
    df["depth_path"] = [
        depth_path_for(p, out_dir).as_posix() for p in df["image_path"]
    ]

    if pipe is None:
        pipe = load_depth_pipeline()

    todo = df if overwrite else df[~df["depth_path"].map(lambda p: Path(p).exists())]
    logger.info(
        "Pseudo-depth: %d of %d rows to process (%d already present)",
        len(todo),
        len(df),
        len(df) - len(todo),
    )

    n_flat, ranges, t0 = 0, [], time.perf_counter()
    for start in range(0, len(todo), batch_size):
        chunk = todo.iloc[start : start + batch_size]
        images = [Image.open(minc_root / p).convert("RGB") for p in chunk["image_path"]]
        preds = pipe(images)
        if isinstance(preds, dict):
            preds = [preds]

        for (_, row), pred in zip(chunk.iterrows(), preds):
            raw = np.asarray(pred["predicted_depth"], dtype=np.float32)
            if raw.ndim == 3:
                raw = raw[0]
            rng = float(raw.max() - raw.min())
            ranges.append(rng)
            if rng < FLAT_RANGE_THRESHOLD:
                n_flat += 1
            dest = Path(row["depth_path"])
            dest.parent.mkdir(parents=True, exist_ok=True)
            np.save(dest, normalise_depth(raw).astype(np.float16))

        done = start + len(chunk)
        if done % (batch_size * 20) == 0 or done == len(todo):
            el = time.perf_counter() - t0
            logger.info(
                "  %d/%d  %.2f s/img  eta %.1f min",
                done,
                len(todo),
                el / done,
                (len(todo) - done) * el / done / 60,
            )

    el = time.perf_counter() - t0
    if len(todo):
        logger.info(
            "Done: %d maps in %.1f s (%.3f s/img) — extrapolates to %.1f min "
            "for the full 35,000",
            len(todo),
            el,
            el / len(todo),
            35_000 * el / len(todo) / 60,
        )
        logger.info(
            "Flat maps (raw range < %.0e): %d/%d (%.1f%%) — expected for "
            "carpet/fabric/paper; these contribute little to the depth loss",
            FLAT_RANGE_THRESHOLD,
            n_flat,
            len(ranges),
            100 * n_flat / max(len(ranges), 1),
        )
    return df


def depth_structure_report(
    manifest: pd.DataFrame, top_n: int = 5
) -> pd.DataFrame:
    """
    Per-class standard deviation of the saved normalised depth maps — a measure
    of how much depth structure each material class actually carries.

    Flat-texture classes should rank lowest. This quantifies the known
    limitation rather than asserting it.
    """
    rows = []
    for cls, g in manifest.groupby("minc_class"):
        stds = [
            float(np.load(p).astype(np.float32).std())
            for p in g["depth_path"]
            if Path(p).exists()
        ]
        if stds:
            rows.append((cls, len(stds), float(np.mean(stds))))
    return (
        pd.DataFrame(rows, columns=["minc_class", "n", "mean_depth_std"])
        .sort_values("mean_depth_std")
        .reset_index(drop=True)
    )


def save_sanity_grid(
    manifest: pd.DataFrame,
    minc_root: Union[str, Path],
    out_path: Union[str, Path] = "outputs/figures/pseudo_depth_sanity.png",
    n: int = 6,
    dpi: int = 150,
    seed: int = 1729,
) -> Path:
    """
    Save a 2 x *n* RGB-over-depth grid for visual inspection, sampling distinct
    material classes so flat and structured cases both appear.
    """
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from PIL import Image

    out_path = Path(out_path)
    out_path.parent.mkdir(parents=True, exist_ok=True)

    have = manifest[manifest["depth_path"].map(lambda p: Path(p).exists())]
    # One row per class where possible, so the grid spans the stiffness range.
    # One image per class (pandas 3 removed groupby.apply(include_groups=),
    # so sample indices per group and select by index instead).
    idx = (
        have.sample(frac=1.0, random_state=seed)
        .drop_duplicates("minc_class")
        .index
    )
    picks = have.loc[idx].sort_values("log10E_target")
    if len(picks) > n:
        step = len(picks) / n
        picks = picks.iloc[[int(i * step) for i in range(n)]]
    elif len(picks) < n:
        picks = have.sample(min(n, len(have)), random_state=seed)

    fig, axes = plt.subplots(2, len(picks), figsize=(2.2 * len(picks), 4.8))
    axes = np.atleast_2d(axes)
    for col, (_, row) in enumerate(picks.iterrows()):
        rgb = Image.open(Path(minc_root) / row["image_path"]).convert("RGB")
        d = np.load(row["depth_path"]).astype(np.float32)
        axes[0, col].imshow(rgb)
        axes[0, col].set_title(row["minc_class"], fontsize=8)
        im = axes[1, col].imshow(d, cmap="viridis", vmin=0, vmax=1)
        axes[1, col].set_title(f"std {d.std():.3f}", fontsize=7)
        for r in (0, 1):
            axes[r, col].axis("off")

    fig.suptitle(
        "Depth Anything V2 pseudo-labels — RELATIVE depth, normalised per image "
        "(no metric scale)",
        fontsize=10,
    )
    fig.colorbar(
        im, ax=axes[1, :].tolist(), fraction=0.025, label="relative depth [0,1]"
    )
    fig.savefig(out_path, dpi=dpi, bbox_inches="tight")
    plt.close(fig)
    get_logger("pseudo_depth").info("Wrote sanity grid: %s", out_path)
    return out_path


def update_manifests(
    manifests: Dict[str, pd.DataFrame],
    manifest_dir: Union[str, Path],
    splits: Iterable[str] = SPLITS,
) -> None:
    """Rewrite the manifest CSVs in place with the ``depth_path`` column added."""
    logger = get_logger("pseudo_depth")
    for s in splits:
        if s not in manifests:
            continue
        p = Path(manifest_dir) / f"{s}.csv"
        manifests[s].to_csv(p, index=False)
        logger.info("Updated %s with depth_path (%d rows)", p, len(manifests[s]))
